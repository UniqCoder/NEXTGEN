"""L4 recognition v0: the physics expert (E3-lite). Family (linear PSK / FSK), order, symbol rate and carrier
from the recording alone, with no training data, so it behaves the same on real recordings as on synthetic ones.

- Symbol rate of a linear modulation: the |x|^2 line generated by the two band edges (the excess-bandwidth
  regions at fc +- Rs/2). Lines produced by structure inside the band (idle patterns, probes, tones) do not
  survive keeping only the edges, which is what fools a plain |x|^2 peak pick on real HF modems.
- Order: decode-fit. Sample symbols at the measured rate and score block-wise M-th order coherence for
  M = 2, 4, 8; the smallest M that explains the symbols wins. Where the channel smears the constellation
  (HF multipath, no equalizer) the orders do not separate and the answer is a candidate set, not a guess.
- FSK: regular, energy-dominant tones; keying rate from instantaneous-frequency transitions.
- Standards: consistent named standards from a small table; the measured rate against the standard's nominal
  one gives the recording chain's clock offset in ppm."""
import numpy as np
from scipy.signal import firwin
from .dsp import rotate, filt0, sample_at
from .measure import occupied_band, band_measure, cfo_power, timing_fit, _peak

BLK = 32                 # symbols per coherence block (tolerates slow phase drift)
ORDER_MIN = 0.5          # best-order coherence needed to decide the order at all (random data: ~0.18)
ORDER_TIE = 0.85         # an order within this fraction of the best counts as explaining the symbols
RATE_CLEAR = 2.0         # the band-edge line must beat the best other rate by this factor to be trusted
FSK_CONC = 0.6           # fraction of in-band energy that must sit on the tones
PSK_NAME = {2: "BPSK", 4: "QPSK", 8: "8PSK"}

# Published PHY signatures (Signal Identification Wiki and the standards). orders: allowed PSK orders.
STANDARDS = [
    {"name": "STANAG 4285", "family": "PSK", "orders": (2, 4, 8), "rate": 2400.0, "carrier": 1800.0},
    {"name": "MIL-STD-188-110A serial", "family": "PSK", "orders": (2, 4, 8), "rate": 2400.0, "carrier": 1800.0},
    {"name": "HFDL", "family": "PSK", "orders": (2, 4, 8), "rate": 1800.0, "carrier": 1440.0},
    {"name": "PSK31", "family": "PSK", "orders": (2,), "rate": 31.25},
    {"name": "PSK63", "family": "PSK", "orders": (2,), "rate": 62.5},
    {"name": "NAVTEX / SITOR-B", "family": "FSK", "tones": 2, "rate": 100.0, "spacing": 170.0},
    {"name": "HF DSC", "family": "FSK", "tones": 2, "rate": 100.0, "spacing": 170.0},
    {"name": "RTTY 45.45 Bd", "family": "FSK", "tones": 2, "rate": 45.45, "spacing": 170.0},
    {"name": "2G ALE (MIL-STD-188-141)", "family": "FSK", "tones": 8, "rate": 125.0, "spacing": 250.0},
]


def _centred(x, fs, fc, bw):
    return filt0(rotate(x, -fc / fs), firwin(513, min(0.99, 0.65 * bw / (fs / 2))).astype(np.float32))


def _line(F, k, ring=200, gap=6):
    r = np.r_[F[max(1, k - ring): k - gap], F[k + gap + 1: k + ring + 1]]
    return float(F[max(0, k - 2): k + 3].max() / (np.median(r) + 1e-30)) if r.size else 0.0


def edge_rate(x, fs, fc, bw):
    """Scan candidate rates in the physically plausible window for a linear modulation of this bandwidth;
    returns (rate, line strength, runner-up strength)."""
    X = np.fft.fft(x.astype(np.complex128))
    f = np.fft.fftfreq(x.size, 1 / fs)
    nfft = 1 << int(np.ceil(np.log2(2 * x.size)))
    # 0.25: non-RRC pulses (PSK31) are wide; 1.6: at low SNR the measured band shrinks as its edges sink into the noise
    grid = np.exp(np.arange(np.log(0.25 * bw), np.log(1.6 * bw), np.log(1.04)))
    scores = []
    for r in grid:
        keep = (np.abs(f - (fc - r / 2)) < 0.2 * r) | (np.abs(f - (fc + r / 2)) < 0.2 * r)
        p = np.abs(np.fft.ifft(np.where(keep, X, 0))) ** 2
        F = np.abs(np.fft.rfft(p - p.mean(), nfft)) ** 2
        a, b = int(0.95 * r / fs * nfft), int(1.05 * r / fs * nfft) + 1
        k = a + int(F[a:b].argmax())
        scores.append((_line(F, k), _peak(F, k) * fs / nfft))
    scores.sort(key=lambda s: -s[0])
    best = scores[0]
    # a line at r/2 cannot come from rate r (no RRC pulse has >100 % excess bandwidth): prefer the fundamental
    half = max((s for s in scores if abs(s[1] / best[1] - 0.5) < 0.04), default=None, key=lambda s: s[0])
    if half and half[0] >= 0.3 * best[0]:
        best = half
    related = lambda r: any(abs(r / best[1] - k) < 0.04 * k for k in (0.5, 1 / 3, 1, 2, 3))
    other = next((s for s in scores if not related(s[1])), (0.0, 0.0))    # harmonics are not rival hypotheses
    return best[1], best[0], other[0]


def coherence(ys, M):
    nb = ys.size // BLK
    if nb == 0:
        return 0.0
    b = ys[: nb * BLK].reshape(nb, BLK).astype(np.complex128)
    return float(np.mean(np.abs((b ** M).sum(1)) / ((np.abs(b) ** M).sum(1) + 1e-30)))


def decode_fit(y, fs, rate, rolloff=0.35):
    """Symbols at the measured rate under each PSK order: {M: (coherence, symbols, cfo, measured rate)}."""
    sps = fs / rate
    nsym = y.size / sps
    out = {}
    for M in (2, 4, 8):
        cfo = cfo_power(y, fs, M)
        yc = rotate(y, -cfo / fs)
        sps_m, t0 = timing_fit(yc, sps, rolloff, int(min(512, max(16, nsym // 8))))
        k = np.arange(int((yc.size - 1 - t0) / sps_m))
        ys = sample_at(yc, t0 + sps_m * k, sps_m, rolloff)
        out[M] = (coherence(ys, M), ys, cfo, fs / sps_m)
    return out


def _fsk(x, fs, lo, hi, fc):
    tones = sorted(band_measure(x, fs, lo, hi)["tones_hz"])
    nper = 4096
    if len(tones) < 2 or x.size < 2 * nper:
        return None
    sp = np.diff(tones)
    spacing = float(np.median(sp))
    if spacing < 4 * fs / nper or np.any(np.abs(sp - spacing) > 0.15 * spacing):
        return None
    seg = x[: x.size // nper * nper].reshape(-1, nper) * np.hanning(nper)
    S = np.fft.fftshift((np.abs(np.fft.fft(seg, axis=1)) ** 2).mean(0))
    f = np.fft.fftshift(np.fft.fftfreq(nper, 1 / fs))
    inb = (f >= lo) & (f <= hi)
    near = np.zeros_like(inb)
    for t in tones:
        near |= np.abs(f - t) < max(spacing / 4, 2 * fs / nper)
    conc = float(S[inb & near].sum() / (S[inb].sum() + 1e-30))
    if conc < FSK_CONC:
        return None
    y = _centred(x, fs, fc, hi - lo)
    fi = np.angle(y[1:] * np.conj(y[:-1])) * fs / (2 * np.pi)          # instantaneous frequency
    L = max(1, int(fs / (8 * spacing)))
    d = np.abs(np.diff(np.convolve(fi, np.ones(L) / L, "same")))       # large at every keying transition
    nfft = 1 << int(np.ceil(np.log2(4 * d.size)))
    F = np.abs(np.fft.rfft(d - d.mean(), nfft)) ** 2
    fr = np.arange(F.size) * fs / nfft
    sel = np.flatnonzero((fr > spacing / 5) & (fr < 1.2 * spacing))
    k = int(sel[F[sel].argmax()])
    return {"family": "FSK", "tones_hz": tones, "spacing_hz": spacing, "rate_hz": _peak(F, k) * fs / nfft,
            "rate_strength": _line(F, k), "tone_energy": conc,
            "modulation": f"{len(tones)}-FSK", "carrier_hz": float(np.mean(tones))}


def _psk(x, fs, lo, hi, fc):
    bw = max(hi - lo, 20.0)
    rate, strength, runner = edge_rate(x, fs, fc, bw)
    y = _centred(x, fs, fc, bw)
    if y.size / (fs / rate) < 4 * BLK:
        return None
    fits = decode_fit(y, fs, rate)
    coh = {M: fits[M][0] for M in fits}
    best = max(coh.values())
    clear = strength >= RATE_CLEAR * runner                          # no order claim at a rate that is not clear
    order = next((M for M in (2, 4, 8) if coh[M] >= ORDER_TIE * best), None) if best >= ORDER_MIN and clear else None
    cands = sorted(({"v": PSK_NAME[M], "p": round(coh[M], 3)} for M in coh), key=lambda c: -c["p"])
    # timing-fit rate (whole-file phase slope) when the symbols are clean; the edge line when they are smeared
    out = {"family": "PSK", "rate_hz": fits[order][3] if order else rate, "rate_strength": strength, "rate_runner_up": runner,
           "coherence": {PSK_NAME[M]: round(coh[M], 3) for M in coh}, "order": order, "rate_clear": bool(clear),
           "modulation": PSK_NAME[order] if order else "PSK (order not separable)" if clear else "PSK (rate uncertain)",
           "candidates": cands,
           "carrier_hz": fc + fits[order][2] if order else fc}
    if order:
        c, ys, *_ = fits[order]
        nb = ys.size // 256                                             # Viterbi-Viterbi phase per 256 symbols
        if nb:
            b = ys[: nb * 256].reshape(nb, 256).astype(np.complex128)
            th = np.angle(-np.sum(b ** order, 1)) / order if order > 1 else 0
            z = (b * np.exp(-1j * np.asarray(th))[:, None]).ravel()
            z = z / np.sqrt(np.mean(np.abs(z) ** 2))
            if order == 2:
                z = z * np.exp(-1j * np.angle(np.mean(z ** 2)) / 2)     # BPSK on the real axis
            out["symbols"] = z.astype(np.complex64)
    return out


def standards(r: dict) -> list[dict]:
    """Every tabled standard consistent with the measured PHY, with the implied clock offset."""
    out = []
    for s in STANDARDS:
        if s["family"] != r["family"] or abs(r["rate_hz"] / s["rate"] - 1) > 0.01:
            continue
        if r["family"] == "PSK" and r.get("order") and r["order"] not in s["orders"]:
            continue
        if r["family"] == "FSK" and (len(r["tones_hz"]) != s["tones"] or abs(r["spacing_hz"] / s["spacing"] - 1) > 0.25):
            continue
        # the clock offset is only meaningful where the rate is measured to ppm precision (PSK timing fit / edge line)
        ppm = round((r["rate_hz"] / s["rate"] - 1) * 1e6, 1) if r["family"] == "PSK" else None
        out.append({"name": s["name"], "ppm": ppm})
    return out


def identify(x: np.ndarray, fs: float) -> dict | None:
    """PHY identification of the strongest emission; None when no emission stands out."""
    band = occupied_band(x, fs)
    if band is None:
        return None
    lo, hi, fc, snr, floor_db = band
    if snr < 3 or hi - lo < 2 * fs / 2048:
        return None
    r = _fsk(x, fs, lo, hi, fc) or _psk(x, fs, lo, hi, fc)
    if r is None:
        return None
    r.update(band_lo_hz=lo, band_hi_hz=hi, centre_hz=fc, snr_db=snr, floor_db=floor_db)
    r["standards"] = standards(r)
    return r
